"""Command line interface.

Used by the Makefile so that ``make seed``, ``make smoke`` and ``make scenarios`` are thin wrappers
around real engine calls rather than shell scripts that could drift from the library.

Subcommands::

    memory-firewall init                 create the database and verify FTS5
    memory-firewall bootstrap            create a tenant + admin, print the token once
    memory-firewall seed                 idempotent synthetic demo corpus (fixed timestamps)
    memory-firewall setup-demo           init + seed + write tokens to .env (used by `make setup`)
    memory-firewall scenarios            run every offline scenario, exit non-zero on failure
    memory-firewall retrieve             guarded retrieval from the shell
    memory-firewall smoke                the blueprint §5 mandatory smoke sequence
    memory-firewall doctor               environment / FTS5 / schema diagnostics
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

from . import __version__
from ._version import DETECTOR_VERSION, POLICY_REVISION
from .config import from_env
from .db import FTS5Unavailable, assert_fts5
from .engine import MemoryFirewallEngine
from .errors import FirewallError
from .identity import Principal
from .scenarios import run_all
from .seed import seed as seed_world

__all__ = ["main"]

DEFAULT_DB = "data/memory-firewall.sqlite3"
ENV_PATH = Path(".env")


def _engine(db: str) -> MemoryFirewallEngine:
    config = from_env()
    config.db_path = Path(db)
    return MemoryFirewallEngine(db, config=config)


def _out(payload: Any) -> None:
    print(json.dumps(payload, indent=2, default=str))


def _write_env(tokens: dict[str, str], db: str) -> Path:
    """Write a gitignored .env with freshly generated local dev tokens.

    An existing .env is never clobbered — a second `make setup` keeps the tokens you already have.
    """
    if ENV_PATH.exists():
        return ENV_PATH
    lines = [
        "# Local development profile for Memory Firewall. GITIGNORED - do not commit.",
        "# Generated by `make setup`. These tokens are random, local-only and grant access to the",
        "# local demo database only. Rotate by deleting this file and the database, then re-running.",
        f"MF_DB_PATH={db}",
        "MF_API_HOST=127.0.0.1",
        "MF_API_PORT=8002",
        "MF_WEB_PORT=5174",
        "MF_ENABLE_UNGUARDED_BASELINE=1",
        "MF_STRICT_REJECT_FORGED_FIELDS=0",
        "MF_LLM_ADAPTER=null",
        "",
        "# Demo principals. Role is server-side state; these are only credentials.",
    ]
    for name, token in tokens.items():
        lines.append(f"MF_TOKEN_{name.replace('-', '_').upper()}={token}")
    lines.append("")
    ENV_PATH.write_text("\n".join(lines), encoding="utf-8")
    ENV_PATH.chmod(0o600)
    return ENV_PATH


def _demo_tokens() -> dict[str, str]:
    """Reuse tokens already present in the environment so setup is idempotent."""
    names = ["support-root", "support-admin", "support-reader", "other-admin", "other-reader"]
    out: dict[str, str] = {}
    for name in names:
        key = "MF_TOKEN_" + name.replace("-", "_").upper()
        value = os.environ.get(key)
        if value:
            out[name] = value
    return out


def cmd_doctor(args: argparse.Namespace) -> int:
    report: dict[str, Any] = {
        "python": sys.version.split()[0],
        "memory_firewall": __version__,
        "detector_version": DETECTOR_VERSION,
        "policy_revision": POLICY_REVISION,
        "database": args.db,
    }
    try:
        assert_fts5()
        report["fts5"] = True
    except FTS5Unavailable as exc:
        report["fts5"] = False
        report["fts5_help"] = str(exc)
        _out(report)
        return 1
    import sqlite3

    report["sqlite_version"] = sqlite3.sqlite_version
    db_path = Path(args.db)
    report["database_exists"] = db_path.exists()
    if db_path.exists():
        engine = _engine(args.db)
        report["schema_version"] = engine.db.schema_version()
        report["manifest_entries"] = engine.manifests.count()
        report["manifest_store"] = str(engine.manifests.path)
    _out(report)
    return 0


def cmd_init(args: argparse.Namespace) -> int:
    engine = _engine(args.db)
    _out(
        {
            "database": str(engine.config.db_path),
            "manifest_store": str(engine.manifests.path),
            "schema_version": engine.db.schema_version(),
            "fts5": True,
        }
    )
    return 0


def cmd_bootstrap(args: argparse.Namespace) -> int:
    engine = _engine(args.db)
    principal, token = engine.bootstrap(tenant_id=args.tenant, admin_id=args.admin)
    _out(
        {
            "tenant_id": principal.tenant_id,
            "principal": principal.id,
            "role": principal.role,
            "token": token,
            "note": "This token is shown once and only its SHA-256 digest is stored.",
        }
    )
    return 0


def cmd_seed(args: argparse.Namespace) -> int:
    engine = _engine(args.db)
    world = seed_world(engine, tokens=_demo_tokens())
    payload = world.as_dict()
    if world.tokens and not args.no_tokens:
        payload["tokens"] = world.tokens
    _out(payload)
    return 0


def cmd_setup_demo(args: argparse.Namespace) -> int:
    engine = _engine(args.db)
    world = seed_world(engine, tokens=_demo_tokens())
    env_path = _write_env(world.tokens, args.db) if world.tokens else ENV_PATH
    _out(
        {
            "database": str(engine.config.db_path),
            "manifest_store": str(engine.manifests.path),
            "schema_version": engine.db.schema_version(),
            "already_seeded": world.already_seeded,
            "env_file": str(env_path),
            "documents": sorted(world.documents),
            "stats": engine.stats(world.admin),
            "next": [
                "make dev        # start API on 127.0.0.1:8002 and dashboard on 127.0.0.1:5174",
                "make smoke      # poison write/retrieve proof via the API",
                "make verify     # the release truth source",
            ],
        }
    )
    return 0


def cmd_scenarios(args: argparse.Namespace) -> int:
    results = run_all()
    if args.json:
        _out(results)
    else:
        for r in results["results"]:
            flag = "PASS" if r["passed"] else "FAIL"
            print(f"{flag}  {r['id']:22} {len(r['checks']):2} checks  {r['name']}")
            for c in r["checks"]:
                if not c["passed"]:
                    print(
                        f"      FAILED: {c['name']} expected={c['expected']!r} "
                        f"observed={c['observed']!r}"
                    )
        total_checks = sum(len(r["checks"]) for r in results["results"])
        print(
            f"\n{results['passed']}/{results['total']} scenarios passed ({total_checks} assertions)"
        )
    return 0 if not results["failed"] else 1


def cmd_retrieve(args: argparse.Namespace) -> int:
    engine = _engine(args.db)
    with engine.db.connect() as conn:
        row = conn.execute(
            "SELECT id, tenant_id, role FROM principals WHERE id = ?", (args.principal,)
        ).fetchone()
    if row is None:
        _out({"error": f"unknown principal '{args.principal}'"})
        return 2
    actor = Principal(id=row["id"], tenant_id=row["tenant_id"], role=row["role"])
    result = engine.retrieve(
        actor, query=args.query, limit=args.limit, include_trace=args.trace and actor.is_admin
    )
    _out(result.as_dict(include_trace=args.trace and actor.is_admin))
    return 0


def cmd_smoke(args: argparse.Namespace) -> int:
    """The blueprint §5 mandatory smoke sequence, run in-process against a disposable database."""
    from .scenarios import run_scenario

    required = [
        "golden-poison",
        "index-bypass",
        "cross-tenant",
        "forged-identity",
        "benign-update",
        "revocation",
    ]
    failures: list[str] = []
    out: list[dict[str, Any]] = []
    for scenario_id in required:
        result = run_scenario(scenario_id)
        out.append(
            {
                "id": result["id"],
                "passed": result["passed"],
                "checks": len(result["checks"]),
                "failed_checks": [c["name"] for c in result["checks"] if not c["passed"]],
            }
        )
        if not result["passed"]:
            failures.append(scenario_id)
    _out(
        {"mandatory_smoke": out, "failed": failures, "verdict": "PASS" if not failures else "FAIL"}
    )
    return 0 if not failures else 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="memory-firewall", description="Memory Firewall administration and demo CLI."
    )
    parser.add_argument("--version", action="version", version=__version__)
    sub = parser.add_subparsers(dest="command", required=True)

    def add_db(p: argparse.ArgumentParser) -> None:
        p.add_argument("--db", default=os.environ.get("MF_DB_PATH", DEFAULT_DB))

    p = sub.add_parser("doctor", help="environment diagnostics")
    add_db(p)
    p.set_defaults(func=cmd_doctor)

    p = sub.add_parser("init", help="create the database and verify FTS5")
    add_db(p)
    p.set_defaults(func=cmd_init)

    p = sub.add_parser("bootstrap", help="create a tenant and its first admin")
    add_db(p)
    p.add_argument("--tenant", default="support")
    p.add_argument("--admin", default="support-root")
    p.set_defaults(func=cmd_bootstrap)

    p = sub.add_parser("seed", help="idempotent synthetic demo corpus")
    add_db(p)
    p.add_argument("--no-tokens", action="store_true", help="do not print tokens")
    p.set_defaults(func=cmd_seed)

    p = sub.add_parser("setup-demo", help="init + seed + write .env")
    add_db(p)
    p.set_defaults(func=cmd_setup_demo)

    p = sub.add_parser("scenarios", help="run all offline scenarios")
    add_db(p)
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_scenarios)

    p = sub.add_parser("smoke", help="mandatory smoke sequence")
    add_db(p)
    p.set_defaults(func=cmd_smoke)

    p = sub.add_parser("retrieve", help="guarded retrieval from the shell")
    add_db(p)
    p.add_argument("query")
    p.add_argument("--principal", default="support-reader")
    p.add_argument("--limit", type=int, default=5)
    p.add_argument("--trace", action="store_true")
    p.set_defaults(func=cmd_retrieve)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return int(args.func(args))
    except FirewallError as exc:
        _out({"error": exc.code, "message": str(exc)})
        return 1


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
